# Generator source for `lib/scry/document/grammar/compiled.ex` -- that
# file is generated, checked in, and must never be hand-edited (see its
# own banner). Run this script (`mix run priv/gen/
# generate_compiled_grammar.exs`) after changing `priv/grammar.aether`,
# then re-run the test suite. There's no automatic staleness check
# between the two -- see `scry_core`'s own identical generator script
# for why (a byte-diff between two separately-generated copies of the
# same grammar spuriously fails; the codegen backend iterates
# `%Aether.Grammar{}`'s own maps, whose iteration order isn't stable
# across VM boots). `grammar_parity_test.exs` is the safety net instead.
#
# One extra step `scry_core`'s own copy of this script doesn't need:
# this package's own fragment has to be parsed and merged with core's
# grammar (`Scry.Core.Grammar.compile_unanalyzed/0` + `Scry.Core.
# GrammarCompose.merge/2`, both existing/unchanged) *before* codegen --
# `Ichor.generate_from_grammar/2`, not `Ichor.generate/3`, is the right
# entry point for an already-parsed-but-unanalyzed `%Aether.Grammar{}`,
# same as `Scry.Document.Grammar.compile/0` already does at (formerly
# the only) runtime.
#
# Why a manually-run `.exs` script, not an automatic Mix compiler:
# see `Scry.Core.Grammar`'s own moduledoc (in `scry_core`) for the full
# "any module calling Ichor.* has to live somewhere Mix compiles
# unconditionally, including as a downstream package's dependency"
# reasoning -- identical here.

frag_path = Scry.Document.Grammar.grammar_path()
{:ok, fragment} = Aether.Parser.parse(File.read!(frag_path), frag_path)
{:ok, core} = Scry.Core.Grammar.compile_unanalyzed()
{:ok, merged} = Scry.Core.GrammarCompose.merge(core, fragment)

body = Ichor.generate_from_grammar(merged, Scry.Document.Actions)

# See `Scry.Core.Grammar`'s own generator script for what/why this does
# -- identical, `Mix.Tasks.Ichor.Gen`'s own `publicize/1`.
publicize = fn body ->
  Macro.postwalk(body, fn
    {:defp, meta, args} -> {:def, meta, args}
    other -> other
  end)
end

text =
  quote do
    defmodule Scry.Document.Grammar.Compiled do
      @moduledoc false
      unquote(publicize.(body))
    end
  end
  |> Macro.to_string()
  |> Code.format_string!()
  |> IO.iodata_to_binary()

banner = """
# Generated by:
#
#     mix run priv/gen/generate_compiled_grammar.exs
#
# Do not edit by hand -- edit priv/grammar.aether, then rerun the
# command above and the test suite instead.
"""

out = Path.join(__DIR__, "../../lib/scry/document/grammar/compiled.ex") |> Path.expand()
File.mkdir_p!(Path.dirname(out))
File.write!(out, banner <> text <> "\n")
Mix.shell().info("* creating #{out}")
